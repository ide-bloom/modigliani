"""Reading and writing profiles as YAML or JSON."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from modigliani.profile.model import Profile


def load_data(path: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    data = json.loads(text) if path.suffix == ".json" else yaml.safe_load(text)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: a profile must be a mapping")
    return data


def load_profile(path: Path) -> Profile:
    return Profile.model_validate(load_data(path))


def dump_profile(profile: Profile, fmt: str = "yaml") -> str:
    data = profile.model_dump(mode="json")
    if fmt == "json":
        return json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    header = (
        "# Modigliani device profile. Schema: docs/profile-schema.md\n"
        "# Generated by `modigliani infer`; review with `modigliani review`.\n"
    )
    return header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def save_profile(profile: Profile, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fmt = "json" if path.suffix == ".json" else "yaml"
    path.write_text(dump_profile(profile, fmt), encoding="utf-8")
